def test_crm_mvp_enhancer_replaces_incomplete_package_manifest() -> None:
    manifest = ensure_crm_next_mvp_manifest(
        manifest=incomplete_next_package_manifest(),
        template_key="crm",
        brief=car_wash_brief(),
    )
    files = {file.path: file.content for file in manifest.files}
    package_json = json.loads(files["package.json"])

    assert package_json["dependencies"]["next"].startswith("^15.")
    assert package_json["dependencies"]["@supabase/supabase-js"].startswith("^2.")
    assert "react-dom" in package_json["dependencies"]
    assert "autoprefixer" in package_json["devDependencies"]
    assert "postcss" in package_json["devDependencies"]
    assert "tailwindcss" in package_json["devDependencies"]
    assert "typescript" in package_json["devDependencies"]
    assert "@types/node" in package_json["devDependencies"]
    assert "@types/react" in package_json["devDependencies"]
    assert "@types/react-dom" in package_json["devDependencies"]
    assert package_json["scripts"]["build"] == "next build"
    assert "jest" not in package_json["devDependencies"]


