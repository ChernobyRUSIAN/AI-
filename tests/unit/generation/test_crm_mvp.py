def test_crm_mvp_enhancer_removes_pages_router_imports_from_app_router_files() -> None:
    manifest = ensure_crm_next_mvp_manifest(
        manifest=app_router_incompatible_manifest(),
        template_key="crm",
        brief=car_wash_brief(),
    )
    app_files = {
        file.path: file.content
        for file in manifest.files
        if file.path.startswith("src/app/")
    }

    assert all("next/router" not in content for content in app_files.values())
    assert 'from "next/navigation"' in app_files["src/app/page.tsx"]
    assert "redirect" in app_files["src/app/page.tsx"]
    assert 'from "next/navigation"' in app_files["src/app/reports/page.tsx"]
    assert app_files["src/app/reports/page.tsx"].startswith('"use client";')


