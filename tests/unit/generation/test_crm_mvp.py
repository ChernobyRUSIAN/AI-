def test_crm_mvp_enhancer_generates_dentistry_crm_without_car_wash_copy() -> None:
    manifest = ensure_crm_next_mvp_manifest(
        manifest=dentistry_stub_manifest(),
        template_key="crm",
        brief=dentistry_brief(),
    )
    files = {file.path: file.content for file in manifest.files}
    generated_content = "\n".join(files.values()).casefold()

    forbidden_domain_terms = [
        "car wash operations",
        "premium wash",
        "wash orders",
        "bay preparation",
        "car wash",
        "vehicle",
    ]

    for forbidden_term in forbidden_domain_terms:
        assert forbidden_term not in generated_content
    assert "dental clinic operations" in files["src/app/dashboard/page.tsx"].casefold()
    assert "patients" in files["src/app/customers/page.tsx"].casefold()
    assert "appointments" in files["src/app/orders/page.tsx"].casefold()
    assert "treatments" in files["src/app/tasks/page.tsx"].casefold()
    assert 'placeholder="Dental cleaning"' in files["src/app/orders/page.tsx"]


